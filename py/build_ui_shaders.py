#!/usr/bin/env python3
"""
Compile py/shaders/UiQuad_v.hlsl and UiQuad_p.hlsl via DXC (SM 6.0)
into ui/acz_ui_shaders.h for embedding in enhancer.asi.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADER_DIR = os.path.join(ROOT, "py", "shaders")
OUT_HEADER = os.path.join(ROOT, "ui", "acz_ui_shaders.h")

DXC_CANDIDATES = [
    r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe",
    r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.22621.0\x64\dxc.exe",
    r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.19041.0\x64\dxc.exe",
    "dxc.exe",
]

def find_dxc():
    for c in DXC_CANDIDATES:
        if os.path.isfile(c):
            return c
    return "dxc.exe"

def compile_shader(dxc, hlsl_path, profile, out_bin):
    cmd = [
        dxc,
        "-T", profile,
        "-E", "main",
        "-O3",
        "-Fo", out_bin,
        hlsl_path,
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"DXC failed for {hlsl_path}:\n{res.stdout}\n{res.stderr}", file=sys.stderr)
        sys.exit(1)
    with open(out_bin, "rb") as f:
        data = f.read()
    os.remove(out_bin)
    return data

def format_array(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i:i+16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)

def main():
    dxc = find_dxc()
    print(f"Using DXC: {dxc}")
    vs_bytes = compile_shader(dxc, os.path.join(SHADER_DIR, "UiQuad_v.hlsl"), "vs_6_0", os.path.join(SHADER_DIR, "_ui_vs.dxil"))
    ps_bytes = compile_shader(dxc, os.path.join(SHADER_DIR, "UiQuad_p.hlsl"), "ps_6_0", os.path.join(SHADER_DIR, "_ui_ps.dxil"))
    print(f"Compiled UiQuad_v ({len(vs_bytes)} bytes), UiQuad_p ({len(ps_bytes)} bytes)")

    header = (
        "#pragma once\r\n"
        "// Auto-generated by py/build_ui_shaders.py — DO NOT EDIT MANUALLY\r\n"
        "#include <cstdint>\r\n\r\n"
        "namespace acz_ui {\r\n\r\n"
        + format_array("kUiQuadVS", vs_bytes).replace("\n", "\r\n") + "\r\n\r\n"
        + format_array("kUiQuadPS", ps_bytes).replace("\n", "\r\n") + "\r\n\r\n"
        "} // namespace acz_ui\r\n"
    )
    os.makedirs(os.path.dirname(OUT_HEADER), exist_ok=True)
    with open(OUT_HEADER, "wb") as f:
        f.write(header.encode("utf-8"))
    print(f"Wrote {OUT_HEADER}")

if __name__ == "__main__":
    main()
